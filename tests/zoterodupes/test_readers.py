def test_deep_rdf_context_is_rejected_instead_of_silently_truncated(tmp_path):
    from rdflib import BNode, Graph, Literal, URIRef
    from notewrench.zoterodupes.readers import DC, DCT, Z
    graph = Graph()
    node = URIRef("urn:example:book")
    graph.add((node, Z.itemType, Literal("book")))
    graph.add((node, DC.title, Literal("Source book")))
    for index in range(14):
        child = BNode()
        graph.add((node, DCT.isPartOf, child))
        graph.add((child, DC.title, Literal(f"Context {index}")))
        node = child
    path = tmp_path / "deep.rdf"
    graph.serialize(path, format="xml")
    with pytest.raises(InputError, match="structural nesting exceeds 12"):
        load_library("library", path)


