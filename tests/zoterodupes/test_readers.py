def test_actively_changed_export_does_not_get_misleading_file_hash(tmp_path, monkeypatch):
    import notewrench.zoterodupes.readers as readers
    file = tmp_path / "live-export.json"
    file.write_text('[{"key":"AAAABBBB","title":"Original"}]')
    original = readers.read_json
    def changing(path, *args, **kwargs):
        payload = original(path, *args, **kwargs)
        path.write_text('[{"key":"AAAABBBB","title":"Modified during read"}]')
        return payload
    monkeypatch.setattr(readers, "read_json", changing)
    with pytest.raises(InputError, match="changed while"):
        load_library("x", file)


