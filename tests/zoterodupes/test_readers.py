def load(tmp_path, data):
    path = tmp_path / "export.json"
    path.write_text(json.dumps(data))
    return load_library("personal", path)


@pytest.mark.parametrize("file,count", [("bbt-001.json", 1), ("bbt-note.json", 2), ("bbt.csl.json", 1), ("zotero_rdf.xml", 2), ("book_and_snapshot.rdf", 1)])
def test_real_upstream_exports(file, count):
    records, _ = load_library("upstream", UPSTREAM / file)
    assert len(records) == count


def test_real_note_and_tags_survive():
    notes, _ = load_library("upstream", UPSTREAM / "bbt-note.json")
    assert "#f%20o" in notes[0].notes[0]
    rdf, _ = load_library("upstream", UPSTREAM / "zotero_rdf.xml")
    book = next(record for record in rdf if record.metadata["type"] == "book")
    assert {note["note"] for note in book.notes} == {"C", "D"}
    assert "http://purl.org/dc/elements/1.1/relation" in book.raw["rdf"]


def test_real_all_types_export(tmp_path):
    # This .js upstream file is pure JSON generated by Zotero's test suite.
    data = json.loads((UPSTREAM / "translatorExport.js").read_text())
    records, _ = load(tmp_path, list(data.values()))
    assert len(records) >= 35
