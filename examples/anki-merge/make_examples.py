"""Regenerate the ``notewrench anki-merge`` sample exports with Anki's headless library.

Needs the ``anki`` package (the headless core, tested with 26.9.4); it never opens a
user's profile. Every temporary collection lives in a temporary directory that is
deleted when the script exits. GUIDs are generated by Anki, so they change on every run.

    python examples/anki-merge/make_examples.py                      # examples/anki-merge/*.txt
    python examples/anki-merge/make_examples.py --out examples/anki-merge/no-guid --without-guid
"""
