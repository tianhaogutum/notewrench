from pathlib import Path
import tempfile
import argparse

from anki.collection import Collection

HERE = Path(__file__).resolve().parent
COURSE = {
    "C01": ["What powers photosynthesis?", "Light", "C01"],
    "C02": ["Capital of Australia?", "Sydney", "C02"],
    "C03": ["DNA shape?", "Double helix", "C03"],
    "C04": ["Retired course topic", "Kept for review", "C04"],
    "C05": ["Student removed this note", "Do not resurrect silently", "C05"],
}


def model(collection, personal=False):
    value = collection.models.new("Course Facts")
    for name in ["Front", "Back", "CourseID"] + (["Personal"] if personal else []):
        collection.models.add_field(value, collection.models.new_field(name))
    template = collection.models.new_template("Card 1")
    template["qfmt"] = "{{Front}}"
    template["afmt"] = "{{FrontSide}}<hr>{{Back}}"
    collection.models.add_template(value, template)
    collection.models.add(value)
    return value


def generate(out=None, with_html=True, with_guid=True, with_metadata=True):
    out = Path(out or HERE).resolve()
    out.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="anki-merge-examples-") as temp:
        for role in ("old", "new", "student"):
            c = Collection(str(Path(temp) / f"{role}.anki2"))
            try:
                m = model(c, role == "student")
                rows = {key: list(values) for key, values in COURSE.items()}
                if role == "new":
                    rows["C01"][0] = "Which energy source powers photosynthesis?"
                    rows["C02"][1] = "Canberra"
                    rows["C03"][1] = "A double-helical molecule"
                    del rows["C04"]
                    rows["C06"] = ["RNA sugar?", "Ribose", "C06"]
                if role == "student":
                    rows["C03"][1] = 'Twisted ladder — my mnemonic<br><img src="dna.svg">'
                    del rows["C05"]
                    rows["S01"] = ["My own question", "Personal answer", "S01"]
                for key, values in rows.items():
                    note = c.new_note(m)
                    note.fields = values + (["Remember this in lecture\n第二行 notes"] if role == "student" else [])
                    note.tags = ["course::biology"] + (["personal"] if role == "student" else [])
                    c.add_note(note, 1)
                c.export_note_csv(out_path=str(out / f"{role}.txt"), limit=None,
                                  with_html=with_html, with_tags=with_metadata, with_deck=with_metadata,
                                  with_notetype=with_metadata, with_guid=with_guid)
            finally:
                c.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--plain", action="store_true")
    parser.add_argument("--without-guid", action="store_true")
    parser.add_argument("--without-metadata", action="store_true")
    args = parser.parse_args()
    generate(args.out, not args.plain, not args.without_guid, not args.without_metadata)
