"""Regenerate the synthetic ``notewrench zotero-dupes`` demonstration files in this folder.

1. Derive ``personal.json`` and ``group.json`` from unmodified upstream Better BibTeX
   fixtures (``tests/zoterodupes/fixtures/upstream``). Every change is an intentional
   synthetic cross-library edit; no network calls.
2. With ``--review``, also rerun ``compare`` and ``finalize`` to refresh ``review/``,
   ``synthetic-decisions.json`` and ``confirmed/`` (needs the ``zotero-dupes`` extra).

Run from a clone of the repository:  python examples/zotero-dupes/make_examples.py [--review]
"""

import copy
import json
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
UPSTREAM = ROOT / "tests" / "zoterodupes" / "fixtures" / "upstream"


def make_inputs():
    item = json.loads((UPSTREAM / "bbt-001.json").read_text())["items"][0]
    personal = copy.deepcopy(item)
    personal.update(key="PERSON01", uri="http://zotero.org/users/100/items/PERSON01", DOI="10.1007/s004450000105")
    personal["notes"] = [{"key": "NOTE0001", "note": "<div><p>Discuss the ash-layer observations at journal club.</p></div>"}]
    personal["attachments"] = [{"key": "PDF00001", "title": "Article PDF", "contentType": "application/pdf", "annotations": [
        {"key": "ANN00001", "annotationType": "highlight", "annotationText": "The 1600 eruption of Huaynaputina", "annotationComment": "Compare the chronology", "annotationPageLabel": "494"}]}]
    group = copy.deepcopy(item)
    group.update(key="GROUP001", uri="http://zotero.org/groups/200/items/GROUP001", DOI="https://doi.org/10.1007/s004450000105")
    group["title"] = group["title"].replace("southern Peru", "Southern Peru")
    group["pages"] = "493-518"
    group["tags"] = [{"tag": "reading-group", "type": 0}, {"tag": "volcanology", "type": 1}]
    group["notes"] = ["<div><p>Group reading: verify the dating assumptions.</p></div>"]
    group["attachments"] = [{"key": "PDF00002", "title": "Annotated PDF", "annotations": [
        {"key": "ANN00002", "annotationType": "highlight", "annotationText": "Huaynaputina", "annotationComment": "Check location", "annotationPageLabel": "493"}]}]
    csl = json.loads((UPSTREAM / "bbt.csl.json").read_text())[0]
    csl.update(id="Olson2006-personal")
    csl_group = copy.deepcopy(csl)
    csl_group.update(id="Olson2006-group", note="Review the indexing terminology", keyword=["cataloguing", "seminar"])
    conflict = copy.deepcopy(group)
    conflict.update(key="GROUP002", uri="http://zotero.org/groups/200/items/GROUP002", itemID=2, DOI="10.1234/different-version", date="2004", itemType="preprint")
    conflict["notes"] = ["<p>This synthetic variant intentionally has a conflicting DOI and date.</p>"]
    conflict["attachments"][0]["key"] = "PDF00003"
    conflict["attachments"][0]["annotations"][0]["key"] = "ANN00003"
    for filename, payload in [("personal.json", {"items": [personal, csl]}), ("group.json", {"items": [group, conflict, csl_group]})]:
        (HERE / filename).write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n")




def build_review_examples():
    sys.path.insert(0, str(ROOT / "src"))
    from notewrench.zoterodupes.cli import main

    with tempfile.TemporaryDirectory(prefix="zotero-dupes-example-") as temp:
        staging = Path(temp)
        review_dir = staging / "review"
        assert main(["compare", "--library", f"personal={HERE / 'personal.json'}",
                     "--library", f"group={HERE / 'group.json'}", "--output", str(review_dir)]) == 0
        target = HERE / "review"
        target.mkdir(exist_ok=True)
        for name in ["review.json", "review.html", "decisions.json"]:
            shutil.copy2(review_dir / name, target / name)
        review = json.loads((review_dir / "review.json").read_text())
        decisions = json.loads((review_dir / "decisions.json").read_text())
        pair = next(pair for pair in review["pairs"] if not pair["warnings"]
                    and all(review["records"][pair[side]]["annotations"] for side in ["left", "right"]))
        decisions["decisions"][pair["id"]].update(
            status="same", preferred=pair["left"],
            comment="Synthetic demonstration decision generated by examples/zotero-dupes/make_examples.py; not an actual human review.")
        decision_file = HERE / "synthetic-decisions.json"
        decision_file.write_text(json.dumps(decisions, indent=2) + "\n")
        confirmed = staging / "confirmed"
        assert main(["finalize", "--review", str(review_dir / "review.json"), "--decisions", str(decision_file),
                     "--output", str(confirmed)]) == 0
        target = HERE / "confirmed"
        target.mkdir(exist_ok=True)
        for name in ["correspondences.json", "correspondences.csv", "suggestions.json"]:
            shutil.copy2(confirmed / name, target / name)


if __name__ == "__main__":
    make_inputs()
    if "--review" in sys.argv[1:]:
        build_review_examples()
